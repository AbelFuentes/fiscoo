import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useState,
  type ReactNode,
} from 'react';
import { setTheme } from '@abelfuentes/ui-controls/theme';

import { useAuth } from '../auth/AuthContext';
import {
  getAvatarSignedUrl,
  getUserPreferences,
  saveUserPreferences,
  type UserPreferences,
  type UserPreferencesInput,
} from '../features/settings/userPreferences';
import { ACCENTS } from '../features/settings/settings.constants';

const AVATAR_URL_TTL_SECONDS = 3600;

interface PreferencesContextValue {
  preferences: UserPreferences | null;
  avatarSrc: string | undefined;
  loading: boolean;
  updatePreferences: (
    updates: Partial<UserPreferencesInput>,
  ) => Promise<void>;
  refreshPreferences: () => Promise<void>;
}

const PreferencesContext =
  createContext<PreferencesContextValue | undefined>(undefined);

interface PreferencesProviderProps {
  children: ReactNode;
}

function applyAccent(accent: UserPreferences['accent']) {
  const [primary, secondary] = ACCENTS[accent];

  document.documentElement.style.setProperty(
    '--ui-accent',
    primary,
  );

  document.documentElement.style.setProperty(
    '--ui-accent-2',
    secondary,
  );
}

export function PreferencesProvider({
  children,
}: PreferencesProviderProps) {
  const { user } = useAuth();

  const [preferences, setPreferences] =
    useState<UserPreferences | null>(null);

  const [loading, setLoading] = useState(true);

  const [avatarSrc, setAvatarSrc] = useState<string | undefined>(
    undefined,
  );

  const [avatarVersion, setAvatarVersion] = useState(0);

  const avatarPath = preferences?.avatar_url ?? null;

  const loadPreferences = useCallback(async () => {
    if (!user) {
      setPreferences(null);
      setLoading(false);
      return;
    }

    setLoading(true);

    try {
      const data = await getUserPreferences(user.id);

      setPreferences(data);

      if (data?.theme) {
        /*
         * This is initial hydration.
         *
         * The theme switch is not listening yet, so the
         * ui-theme-change event generated by setTheme()
         * will NOT be persisted again.
         */
        setTheme(data.theme, {
          animate: false,
        });
      }

      if (data?.accent) {
        applyAccent(data.accent);
      }
    } catch (error) {
      console.error(
        'Failed to load user preferences',
        error,
      );
    } finally {
      setLoading(false);
    }
  }, [user]);

  useEffect(() => {
    void loadPreferences();
  }, [loadPreferences]);

  const updatePreferences = useCallback(
    async (
      updates: Partial<UserPreferencesInput>,
    ) => {
      if (!user) {
        return;
      }

      const current: UserPreferencesInput = preferences
        ? {
            user_id: preferences.user_id,
            first_name: preferences.first_name,
            last_name: preferences.last_name,
            bio: preferences.bio,
            language: preferences.language,
            avatar_url: preferences.avatar_url,
            theme: preferences.theme,
            accent: preferences.accent,
            email_notifications:
              preferences.email_notifications,
            push_notifications:
              preferences.push_notifications,
            mention_notifications:
              preferences.mention_notifications,
            activity_summary:
              preferences.activity_summary,
          }
        : {
            user_id: user.id,
            first_name: '',
            last_name: '',
            bio: '',
            language: 'es',
            avatar_url: null,
            theme: 'light',
            accent: 'indigo',
            email_notifications: true,
            push_notifications: false,
            mention_notifications: true,
            activity_summary: 'weekly',
          };

      const next: UserPreferencesInput = {
        ...current,
        ...updates,
        user_id: user.id,
      };

      const saved = await saveUserPreferences(next);

      setPreferences(saved);

      if ('avatar_url' in updates) {
        setAvatarVersion((version) => version + 1);
      }

      if (saved.accent) {
        applyAccent(saved.accent);
      }

      /*
       * Do NOT call setTheme() here.
       *
       * When the user clicks the theme switch, ui-controls
       * has already changed the theme before this function
       * is called.
       */
    },
    [preferences, user],
  );

  const refreshPreferences = useCallback(async () => {
    await loadPreferences();
  }, [loadPreferences]);

  useEffect(() => {
    /*
     * Do not listen while preferences are being hydrated.
     *
     * This prevents the initial setTheme() from being treated
     * as a user action.
     */
    if (!user || loading) {
      return;
    }

    const handleThemeChange = (event: Event) => {
      const customEvent = event as CustomEvent<{
        theme: 'light' | 'dark';
      }>;

      const theme = customEvent.detail?.theme;

      if (theme !== 'light' && theme !== 'dark') {
        return;
      }

      void updatePreferences({
        theme,
      }).catch((error) => {
        console.error(
          'Failed to save theme preference',
          error,
        );
      });
    };

    window.addEventListener(
      'ui-theme-change',
      handleThemeChange,
    );

    return () => {
      window.removeEventListener(
        'ui-theme-change',
        handleThemeChange,
      );
    };
  }, [loading, updatePreferences, user]);

  /*
   * Avatars live in a private bucket: sign a short-lived URL and
   * refresh it before it expires.
   */
  useEffect(() => {
    if (!avatarPath) {
      setAvatarSrc(undefined);
      return;
    }

    let cancelled = false;
    let timer: number | undefined;

    const sign = async () => {
      try {
        const url = await getAvatarSignedUrl(
          avatarPath,
          AVATAR_URL_TTL_SECONDS,
        );

        if (cancelled) return;

        setAvatarSrc(url);

        timer = window.setTimeout(
          sign,
          (AVATAR_URL_TTL_SECONDS - 300) * 1000,
        );
      } catch (error) {
        console.error('Failed to sign avatar url', error);

        if (!cancelled) {
          setAvatarSrc(undefined);
        }
      }
    };

    void sign();

    return () => {
      cancelled = true;

      if (timer) {
        window.clearTimeout(timer);
      }
    };
  }, [avatarPath, avatarVersion]);

  /*
   * Do not render the application until the user's
   * preferences have been hydrated.
   *
   * This guarantees that Dashboard and Settings start
   * with the correct theme and accent.
   *
   * Keep this early return AFTER every hook above:
   * hooks must run in the same order on every render.
   */
  if (loading) {
    return null;
  }

  return (
    <PreferencesContext.Provider
      value={{
        preferences,
        avatarSrc,
        loading,
        updatePreferences,
        refreshPreferences,
      }}
    >
      {children}
    </PreferencesContext.Provider>
  );
}

export function usePreferences() {
  const context = useContext(PreferencesContext);

  if (!context) {
    throw new Error(
      'usePreferences must be used inside PreferencesProvider',
    );
  }

  return context;
}
